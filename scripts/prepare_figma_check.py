"""Prepare the exact Figma check outline from the saved geometry response."""
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
base = ROOT / 'qa/figma-source'
data = json.loads((base / 'check-geometry.json').read_text(encoding='utf-8-sig'))
frame = data['nodes']['2:1992']['document']
vector = frame['children'][0]
path = vector['strokeGeometry'][0]['path']
dx = vector['absoluteBoundingBox']['x'] - frame['absoluteBoundingBox']['x']
dy = vector['absoluteBoundingBox']['y'] - frame['absoluteBoundingBox']['y']
tokens = re.findall(r'[MLCZ]|[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?', path)
methods = {'M': ('moveTo', 2), 'L': ('lineTo', 2), 'C': ('cubicTo', 6), 'Z': ('close', 0)}
commands = []
i = 0
while i < len(tokens):
    command = tokens[i]
    method, count = methods[command]
    values = tokens[i + 1:i + 1 + count]
    assert len(values) == count
    commands.append(f'    ..{method}({", ".join(values)})')
    i += count + 1
dart = """// Generated by scripts/prepare_figma_check.py from Figma nodes 2:1992 / 2:1993.
import 'package:flutter/material.dart';

class FigmaCheck extends StatelessWidget {
  const FigmaCheck({super.key});
  @override
  Widget build(BuildContext context) => const SizedBox(width: 20, height: 20,
    child: CustomPaint(painter: _FigmaCheckPainter()));
}

class _FigmaCheckPainter extends CustomPainter {
  const _FigmaCheckPainter();
  static final _paint = Paint()..color = Colors.black;
  static final _path = Path()
""" + '\n'.join(commands) + f""";
  @override
  void paint(Canvas canvas, Size size) {{
    canvas.save();
    canvas.scale(size.width / 20, size.height / 20);
    canvas.translate({dx}, {dy});
    canvas.drawPath(_path, _paint);
    canvas.restore();
  }}
  @override
  bool shouldRepaint(covariant _FigmaCheckPainter oldDelegate) => false;
}}
"""
(ROOT / 'apps/mobile/lib/figma_check.dart').write_text(dart, encoding='utf-8')
svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 20 20">'
       f'<path transform="translate({dx} {dy})" fill="#000000" d="{path}"/></svg>')
(base / 'artwork/check.svg').write_text(svg, encoding='utf-8')
manifest = json.loads((base / 'manifest.json').read_text(encoding='utf-8'))
manifest['assets'] = [e for e in manifest['assets'] if e.get('nodeId') != frame['id']]
manifest['assets'].append({'nodeId': frame['id'], 'vectorNodeId': vector['id'],
    'name': frame['name'], 'path': 'artwork/check.svg', 'dimensions': [20, 20],
    'bounds': frame['absoluteBoundingBox'], 'sourceVersion': data['version'],
    'exportMethod': 'exact strokeGeometry, rendered natively by FigmaCheck',
    'sha256': hashlib.sha256(svg.encode('utf-8')).hexdigest()})
(base / 'manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
index_path = base / 'index.html'
index = index_path.read_text(encoding='utf-8')
if 'artwork/check.svg' not in index:
    index = index.replace('</main>', '<article><h2>Source checkmark</h2><p>2:1992 / 2:1993 - exact stroke geometry</p>'
                          '<a href="artwork/check.svg"><img src="artwork/check.svg" alt="Source checkmark" '
                          'style="background:#ffd700;width:60px;height:60px"></a></article></main>')
    index_path.write_text(index, encoding='utf-8')
print('Prepared exact source check geometry as SVG and Flutter path.')
